"""LoL の .ENG（索引＋圧縮文字列）を読む"""
import struct
T1 = bytes([0x20,0x65,0x74,0x61,0x69,0x6E,0x6F,0x73,0x72,0x6C,0x68,0x63,0x64,0x75,0x70,0x6D])
T2 = bytes([0x74,0x61,0x73,0x69,0x6F,0x20,0x77,0x62,0x20,0x72,0x6E,0x73,0x64,0x61,0x6C,0x6D,0x68,0x20,0x69,0x65,0x6F,0x72,0x61,0x73,0x6E,0x72,0x74,0x6C,0x63,0x20,0x73,0x79,0x6E,0x73,0x74,0x63,0x6C,0x6F,0x65,0x72,0x20,0x64,0x74,0x67,0x65,0x73,0x69,0x6F,0x6E,0x72,0x20,0x75,0x66,0x6D,0x73,0x77,0x20,0x74,0x65,0x70,0x2E,0x69,0x63,0x61,0x65,0x20,0x6F,0x69,0x61,0x64,0x75,0x72,0x20,0x6C,0x61,0x65,0x69,0x79,0x6F,0x64,0x65,0x69,0x61,0x20,0x6F,0x74,0x72,0x75,0x65,0x74,0x6F,0x61,0x6B,0x68,0x6C,0x72,0x20,0x65,0x69,0x75,0x2C,0x2E,0x6F,0x61,0x6E,0x73,0x72,0x63,0x74,0x6C,0x61,0x69,0x6C,0x65,0x6F,0x69,0x72,0x61,0x74,0x70,0x65,0x61,0x6F,0x69,0x70,0x20,0x62,0x6D])

def decode1(raw):
    out = bytearray()
    for c in raw:
        if c & 0x80:
            c &= 0x7F
            out.append(T1[(c & 0x78) >> 3]); out.append(T2[c])
        else:
            out.append(c)
    return bytes(out)

def decode2(s):
    out = bytearray(); i = 0
    while i < len(s):
        if s[i] == 0x1B:
            i += 1; out.append((s[i] + 0x7F) & 0xFF)
        else:
            out.append(s[i])
        i += 1
    return bytes(out)

def read_eng(data):
    first = struct.unpack_from('<H', data, 0)[0]
    n = first // 2
    res = []
    for i in range(n):
        o = struct.unpack_from('<H', data, i*2)[0]
        e = data.index(b'\0', o)
        raw = data[o:e]
        res.append((raw, decode2(decode1(raw))))
    return res
